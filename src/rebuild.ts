// Generates the commented plain-tidyverse block that rebuilds the coding sheet from the original
// data file plus the codes file. House style: a comment on every step, one verb per line after
// each %>%, and read_csv / pivot_wider / left_join. The original file is only read, never
// written, which the comments say out loud.
//
// The coding sheet is the table of recorded codes: one row per item, one column per codebook
// variable. The codebook is the rules document and is never written as data; the block says so,
// so a student never confuses the two (owner, 2026-10-28).
//
// The join key (code parity, 2026-10-28) is the item's own id when the data has one, so a code
// stays on its item even if the file's rows are put in another order:
//   - a short whole-number id (the course chat's id): the code ids are turned into numbers, so
//     coded_data keeps the id as a number and joins onto the course tables as before;
//   - any other id (text, or a long number such as a tweet id): the id is read as text on both
//     sides, so no digit is lost;
//   - no id column: row position (row_number()), as in 0.5.4.

import { LoadedData } from './dataTypes';

export interface RebuildInputs {
  /** Path to the original CSV, relative to the workspace folder, forward slashes. */
  dataRelPath: string;
  /** Path to the codes CSV, relative to the workspace folder, forward slashes. */
  codesRelPath: string;
  /** Path the coding sheet CSV is saved to, relative to the workspace folder, forward slashes. */
  sheetRelPath?: string;
  addedRowId: boolean;
  origin: LoadedData['origin'];
  sourceExpr?: string;
  /** The data column the codes are keyed on (LoadedData.rowIdField). Defaults to row_id. */
  idColumn?: string;
  /** Every id is a whole number short enough to be exact as a number in R (15 digits or fewer). */
  numericIds?: boolean;
  /** Coding column names (no longer printed: the block is written once and must not go stale). */
  codingColumns?: string[];
}

function q(s: string): string {
  return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

/** True when every id is a whole number R holds exactly as a number. */
export function idsAreShortNumbers(ids: string[]): boolean {
  return ids.length > 0 && ids.every((v) => /^-?\d{1,15}$/.test(v));
}

/**
 * The coding sheet's file name: data/derived/coding-sheet.csv for the coding sample (or a file
 * already called coding-sheet), and <name>-coding-sheet.csv for anything else, so two coded files
 * never overwrite each other's sheet.
 */
export function codingSheetPath(name: string): string {
  return /^coding[-_](sample|sheet)$/i.test(name) ? 'data/derived/coding-sheet.csv' : `data/derived/${name}-coding-sheet.csv`;
}

export function rebuildChunk(input: RebuildInputs): string {
  const key = input.idColumn ?? 'row_id';
  const byPosition = input.addedRowId;
  const asText = !byPosition && !input.numericIds;
  const sheet = input.sheetRelPath;
  const lines: string[] = [];
  lines.push('# ---- Rebuild your coding sheet from your codes ----');
  lines.push('# Your coding sheet is the table of codes: one row per item, one column per variable in your');
  lines.push('# codebook. (The codebook is the document of rules; it is not a data file.) This block reads');
  lines.push('# the data you coded and the codes you entered in the data viewer, and joins them by ' + (byPosition ? 'row.' : `${key}.`));
  lines.push('# Your original data file is never changed. Generated by the AURA Lab R Companion.');
  lines.push('');
  lines.push('library(tidyverse)');
  lines.push('');

  if (input.origin === 'rdataframe' && input.sourceExpr) {
    lines.push(`# 1. Read the data you coded (a copy of ${input.sourceExpr}, saved when you opened the viewer).`);
  } else {
    lines.push('# 1. Read the data you coded.');
  }
  if (byPosition) {
    lines.push(`original <- read_csv(${q(input.dataRelPath)}) %>%`);
    lines.push('  mutate(row_id = as.character(row_number()))   # numbers each row, because your data has no id column');
  } else if (asText) {
    lines.push(`#    ${key} is read as text, so a long id keeps every digit.`);
    lines.push('original <- read_csv(');
    lines.push(`  ${q(input.dataRelPath)},`);
    lines.push(`  col_types = cols(${key} = col_character())`);
    lines.push(')');
  } else {
    lines.push(`original <- read_csv(${q(input.dataRelPath)})`);
  }
  lines.push('');

  lines.push('# 2. Read your codes. Each row is one coded cell: which item, which variable, which code.');
  lines.push('hand_codes <- read_csv(');
  lines.push(`  ${q(input.codesRelPath)},`);
  lines.push('  col_types = cols(.default = col_character())');
  lines.push(')');
  lines.push('');

  lines.push('# 3. Spread the codes into one column per codebook variable.');
  lines.push('wide_codes <- hand_codes %>%');
  lines.push('  pivot_wider(');
  lines.push('    id_cols = row_id,');
  lines.push('    names_from = column,');
  lines.push('    values_from = value');
  if (!byPosition && !asText) {
    lines.push('  ) %>%');
    lines.push(`  mutate(row_id = as.numeric(row_id))   # ${key} is a number in your data, so the code ids become numbers too`);
  } else {
    lines.push('  )');
  }
  lines.push('');

  const by = key === 'row_id' ? 'join_by(row_id)' : `join_by(${key} == row_id)`;
  lines.push(`# 4. Join your codes onto the data by ${byPosition ? 'row' : key}. If your file already has an empty column for a`);
  lines.push('#    codebook variable (the coding sheet template does), it is dropped first so your codes fill it.');
  lines.push('coded_data <- original %>%');
  lines.push('  select(-any_of(setdiff(names(wide_codes), "row_id"))) %>%');
  lines.push(`  left_join(wide_codes, by = ${by}) %>%`);
  lines.push('  relocate(any_of(names(original)))');
  lines.push('');

  if (sheet) {
    lines.push('# 5. Save the coding sheet as a CSV file. This is the file you hand in with your coded data.');
    lines.push('#    Prints nothing.');
    lines.push(`write_csv(coded_data, ${q(sheet)})`);
    lines.push('');
  }

  // No column list here: the block is written once and keeps reading new codes, so a list would go stale
  lines.push('# coded_data now has your original columns plus one column for each variable you coded.');
  lines.push('coded_data');
  lines.push('');
  return lines.join('\n');
}
