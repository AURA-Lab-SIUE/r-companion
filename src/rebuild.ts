// Generates the commented plain-tidyverse chunk that rebuilds the coded data from the original
// file plus the codes file. House style: library at the top, a comment on every block, one verb
// per line after each %>%, and read_csv / pivot_wider / left_join by row_id. The original file is
// only read, never written, which the comments say out loud.
//
// row_id is coerced to character on both sides so a synthesized integer id and a file-provided id
// join the same way and read_csv's type guess never breaks the join.

import { LoadedData } from './dataTypes';

export interface RebuildInputs {
  /** Path to the original CSV, relative to the workspace folder, forward slashes. */
  dataRelPath: string;
  /** Path to the codes CSV, relative to the workspace folder, forward slashes. */
  codesRelPath: string;
  addedRowId: boolean;
  origin: LoadedData['origin'];
  sourceExpr?: string;
  /** Coding column names, for the closing comment only. */
  codingColumns: string[];
}

function q(s: string): string {
  return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

export function rebuildChunk(input: RebuildInputs): string {
  const lines: string[] = [];
  lines.push('# Rebuild your coded data from the original file plus your codes.');
  lines.push('# This reads BOTH files and joins them by row_id, so your original data file is never changed.');
  lines.push('# Generated by the AURA Lab R Companion. You can read it, run it, and keep it.');
  lines.push('');
  lines.push('library(tidyverse)');
  lines.push('');

  if (input.origin === 'rdataframe' && input.sourceExpr) {
    lines.push(`# 1. Read the original data (a snapshot of ${input.sourceExpr}, saved when you opened the viewer).`);
  } else {
    lines.push('# 1. Read the original data.');
  }
  if (input.addedRowId) {
    lines.push(`original <- read_csv(${q(input.dataRelPath)}) %>%`);
    lines.push('  mutate(row_id = as.character(row_number()))   # row_id added because your data had none');
  } else {
    lines.push(`original <- read_csv(${q(input.dataRelPath)}) %>%`);
    lines.push('  mutate(row_id = as.character(row_id))');
  }
  lines.push('');

  lines.push('# 2. Read your codes. Each row is one coded cell.');
  lines.push(`codes <- read_csv(`);
  lines.push(`  ${q(input.codesRelPath)},`);
  lines.push('  col_types = cols(row_id = col_character(), value = col_character())');
  lines.push(')');
  lines.push('');

  lines.push('# 3. Spread the long codes into one column per coding variable.');
  lines.push('wide_codes <- codes %>%');
  lines.push('  pivot_wider(');
  lines.push('    id_cols = row_id,');
  lines.push('    names_from = column,');
  lines.push('    values_from = value');
  lines.push('  )');
  lines.push('');

  lines.push('# 4. Join your codes back onto the original data by row_id.');
  lines.push('coded_data <- original %>%');
  lines.push('  left_join(wide_codes, by = "row_id")');
  lines.push('');

  const cols = input.codingColumns.length ? input.codingColumns.join(', ') : '(none yet)';
  lines.push(`# coded_data now has your original columns plus your coding columns: ${cols}.`);
  lines.push('coded_data');
  lines.push('');
  return lines.join('\n');
}
